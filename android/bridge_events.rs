// Rust本体と生成されるOSアダプターが共有する通知番号。
macro_rules! events {
    ($($name:ident = $value:literal),* $(,)?) => {
        $(pub const $name: i32 = $value;)*
        #[allow(dead_code)]
        pub const ALL: &[(&str, i32)] = &[$((stringify!($name), $value)),*];
    };
}
