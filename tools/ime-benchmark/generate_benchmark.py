def num_yomi(n):
    if n == 0:
        return "ぜろ"
    if n >= 10000:
        man = n // 10000
        rest = n % 10000
        return num_yomi(man) + "まん" + (num_yomi(rest) if rest else "")
    s = ""
    s += _THOU[(n // 1000) % 10]
    s += _HUND[(n // 100) % 10]
    s += _TENS[(n // 10) % 10]
    s += _ONES[n % 10]
    return s

def NUM(n):
    return (str(n), num_yomi(n))

