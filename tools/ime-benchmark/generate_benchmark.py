# ---------- カテゴリ1: 基本変換 ----------
def gen_basic(rng):
    col = Collector("基本変換", 1000, rng)
    col.caps = {"基本文": 350, "同音異義語": 300, "形容詞": 150, "文末表現": 200}
    # A: 時+人+場所+名詞+動詞 (組合せが膨大なのでランダムサンプリング)
    for _ in range(20000):
        if col.full():
            break
        t, p, pl, n, v = rng.choice(TIMES), rng.choice(PEOPLE), rng.choice(PLACES), rng.choice(NOUNS), rng.choice(VERBS_OBJ)
        col.add(C(t, p, L("は"), pl, L("で"), n, L("を"), v, L("。")), "基本文")
        if col.sub_counts.get("基本文", 0) >= 350:
            break
    # B: 同音異義語を文脈で
    ctx = [L("を見た"), L("について調べた"), L("の話を聞いた"), L("を思い出した"), L("の意味を調べた"), L("について考えた")]
    combos2 = []
    for group in HOMOPHONES:
        for w in group:
            for c in ctx:
                for t in TIMES:
                    combos2.append(C(t, L("、"), w, c, L("。")))
    col.fill_from(combos2, "同音異義語")
    # C: 形容詞文
    combos3 = (C(t, L("の"), pl, L("は"), a, L("。")) for t, pl, a in itertools.product(TIMES, PLACES, ADJS))
    col.fill_from(combos3, "形容詞")
    # D: 依頼形 (て形+ください等)
    verbs_te = [W("買って","かって"),W("読んで","よんで"),W("書いて","かいて"),W("見て","みて"),W("聞いて","きいて"),W("作って","つくって"),W("食べて","たべて"),W("飲んで","のんで"),W("探して","さがして"),W("直して","なおして"),W("開けて","あけて"),W("閉めて","しめて"),W("持ってきて","もってきて"),W("片付けて","かたづけて"),W("並べて","ならべて"),W("数えて","かぞえて")]
    tails = [L("ください"), L("ほしいです"), L("もらえますか"), L("くれませんか"), L("くださいね")]
    combos4 = (C(t, L("までに"), n, L("を"), v, tail, L("。")) for t, n, v, tail in itertools.product(TIMES, NOUNS, verbs_te, tails))
    col.fill_from(combos4, "文末表現")
    return col.rows

