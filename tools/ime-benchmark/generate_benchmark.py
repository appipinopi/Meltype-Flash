# part = (surface, reading)
def C(*parts):
    """partsを連結して (surface, reading) を返す"""
    return ("".join(p[0] for p in parts), "".join(p[1] for p in parts))

def L(text):  # そのまま打つ文字 (英字/記号など、読み=表面)
    return (text, text)

def W(surface, reading):
    return (surface, reading)

class Collector:
    def __init__(self, category, target, rng):
        self.category = category
        self.target = target
        self.rng = rng
        self.rows = []
        self.seen = set()
        self.caps = {}       # subcategory -> 上限 (多様性確保のため)
        self.sub_counts = {}
    def add(self, part, subcategory):
        surface, reading = part
        key = (surface, reading)
        if key in self.seen or not surface:
            return False
        if subcategory in self.caps and self.sub_counts.get(subcategory, 0) >= self.caps[subcategory]:
            return False
        self.sub_counts[subcategory] = self.sub_counts.get(subcategory, 0) + 1
        self.seen.add(key)
        self.rows.append({
            "category": self.category,
            "subcategory": subcategory,
            "input": reading,
            "expected": surface,
        })
        return True
    def full(self):
        return len(self.rows) >= self.target
    def fill_from(self, combos, subcategory, shuffle=True):
        combos = list(combos)
        if shuffle:
            self.rng.shuffle(combos)
        for part in combos:
            if self.full():
                break
            self.add(part, subcategory)

